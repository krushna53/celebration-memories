export function checkoutPhone(country: string, number: string) {
  let clean = number.replace(/[\s().-]/g, "");
  if (clean.startsWith("+")) return clean;
  if (clean.startsWith("00")) return "+" + clean.slice(2);
  const prefix = NATIONAL_PREFIXES[country];
  if (prefix && clean.startsWith(prefix[0]) && prefix[1].includes(clean.length - prefix[0].length)) {
    clean = clean.slice(prefix[0].length);
  }
  return "+" + (CALLING_CODES[country] ?? "91") + clean;
}
